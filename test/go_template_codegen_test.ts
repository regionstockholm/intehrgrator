Deno.test("go-template codegen from Blockly state with xml_element", () => {
  const model = createEmptyModel("test");
  const blocklyState = {
    blocks: {
      blocks: [
        {
          type: "xml_element",
          fields: { TAG: "Note" },
          inputs: {
            TEXT: {
              block: {
                type: "source_query",
                fields: { EXPRESSION: "path/to/value|value" },
              },
            },
          },
        },
      ],
    },
  };
  const output = generateGoTemplate(model, { blocklyState });
  assert(output.includes("<Note>"), "should emit XML open tag");
  assert(output.includes("</Note>"), "should emit XML close tag");
  assert(output.includes('index .Data "path/to/value|value"'), "should emit index .Data for source query");
});

Deno.test("go-template codegen from Blockly state with controls_if", () => {
  const model = createEmptyModel("test");
  const blocklyState = {
    blocks: {
      blocks: [
        {
          type: "controls_if",
          extraState: { elseIfCount: 0, hasElse: false },
          inputs: {
            IF0: {
              block: {
                type: "logic_compare",
                fields: { OP: "EQ" },
                inputs: {
                  A: { block: { type: "source_query", fields: { EXPRESSION: "symptom|value" } } },
                  B: { block: { type: "text", fields: { TEXT: "Ja" } } },
                },
              },
            },
            DO0: {
              block: {
                type: "xml_element",
                fields: { TAG: "TextKeyWord" },
                inputs: {
                  TEXT: { block: { type: "text", fields: { TEXT: "Symptom present" } } },
                },
              },
            },
          },
        },
      ],
    },
  };
  const output = generateGoTemplate(model, { blocklyState });
  assert(output.includes("if eq"), "should emit if eq condition");
  assert(output.includes('(index .Data "symptom|value")'), "source query in condition");
  assert(output.includes('"Ja"'), "comparison value");
  assert(output.includes("<TextKeyWord>"), "conditional XML");
  assert(output.includes("{{- end }}"), "end block");
});

