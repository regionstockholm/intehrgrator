export interface GoEmitContext {
  kind: "xml" | "json" | "text";
  loopVar?: string;
}

export function registerGoTemplateExportAdapter(): void {
  registerExportTargetAdapter({
    id: "go-template",
    extension: "tmpl",
    mime: "text/x-go-template",
    generate(model, options) {
      if (options?.blocklyState) {
        const fromCanvas = generateGoTemplateFromBlocklyState(
          options.blocklyState,
          model,
          options.skeleton,
        );
        if (fromCanvas) return fromCanvas;
      }
      return generateGoTemplate(model, { blocklyState: options?.blocklyState });
    },
  });
}

export function generateGoTemplateFromBlocklyState(
  state: unknown,
  model: MappingModel,
  skeleton?: SkeletonNode[],
): string | null {
  if (!state || typeof state !== "object") return null;
  const workspace = new Blockly.Workspace();
  try {
    const snapshot = JSON.parse(JSON.stringify(state)) as Record<string, unknown>;
    let generated: string | null = null;
    runWithoutBlocklyEvents(() => {
      registerSchemaTypesFromState(snapshot);
      if (skeleton?.length) registerSchemaBlocksFromSkeleton(skeleton);
      Blockly.serialization.workspaces.load(snapshot, workspace);
      generated = generateGoTemplateFromWorkspace(workspace, model);
    });
    return generated;
  } catch (err) {
    console.warn("Go template codegen from Blockly failed; falling back", err);
    return null;
  } finally {
    workspace.dispose();
  }
}

export function generateGoTemplateFromWorkspace(
  workspace: Workspace,
  model: MappingModel,
): string | null {
  const instanceRoot = findInstanceRootUnderStart(workspace);
  const roots = workspace.getTopBlocks(true).filter((block) =>
    block.type !== DEFAULTS_BLOCK_TYPE &&
    block.type !== "maps_create_with" &&
    block.type !== CONVERSION_START_TYPE
  );
  const helpers = roots.filter((block) => isGoTemplateDefine(block));
  const product = instanceRoot ??
    roots.find((block) => block.type === "composition") ??
    roots.find((block) => isRmContainerBlockType(block.type)) ??
    roots.find((block) =>
      isSchemaStructureBlock(block) ||
      block.type === "json_object" ||
      block.type === "xml_element" ||
      block.type === TEXT_DOCUMENT_BLOCK_TYPE
    ) ??
    roots.find((block) => !isGoTemplateDefine(block));

  if (!product && !helpers.length) return null;

  const kind = product ? productKind(product, model) : "text";
  const ctx: GoEmitContext = { kind };
  const parts: string[] = [
    `{{- /* Generated by intEHRgrator — Go text/template Conversion Script */ -}}`,
    `{{- /* Target: ${model.templateId || "free-form"} */ -}}`,
    `{{- /* Source: Blockly canvas (regenerated when the mapping editor changes) */ -}}`,
  ];
  for (const helper of helpers) {
    if (helper === product) continue;
    const text = String(helper.getFieldValue("TEXT") ?? "");
    if (text.trim()) parts.push(text);
  }
  if (product) {
    const body = emitProduct(product, ctx, 0);
    if (body.trim()) parts.push(body);
  }
  return parts.join("\n");
}

function isGoTemplateDefine(block: Block): boolean {
  if (block.type !== "text_code") return false;
  const lang = String(block.getFieldValue("LANG") ?? "");
  const text = String(block.getFieldValue("TEXT") ?? "");
  return lang === "go-template" && text.includes("define ");
}

function productKind(block: Block, model: MappingModel): GoEmitContext["kind"] {
  if (block.type === TEXT_DOCUMENT_BLOCK_TYPE) return "text";
  if (block.type === "xml_element") return "xml";
  if (block.type === "json_object" || block.type === "json_array") return "json";
  if (isSchemaStructureBlock(block) || block.type.startsWith("schema_")) {
    if (model.targetFormat === "xml-schema") return "xml";
    if (model.targetFormat === "json-schema") return "json";
    const extra = schemaExtraStateOf(block);
    if (extra?.xmlAttributes?.length) return "xml";
    if (extra?.fields?.some((field) => field.xmlKind)) return "xml";
    const targetType = String(block.getFieldValue("TARGET_TYPE") ?? "").toLowerCase();
    if (targetType.includes("xml")) return "xml";
    return "json";
  }
  return "json";
}

function emitProduct(block: Block, ctx: GoEmitContext, indent: number): string {
  if (block.type === TEXT_DOCUMENT_BLOCK_TYPE) {
    const value = block.getInputTargetBlock("VALUE");
    return value ? emitFragment(value, { ...ctx, kind: "text" }, indent) : "";
  }
  if (ctx.kind === "xml") return emitXml(block, ctx, indent);
  return emitJson(block, ctx, indent);
}

function emitFragment(block: Block, ctx: GoEmitContext, indent: number): string {
  if (block.type === "for_each_source") return emitForEach(block, ctx, indent);
  if (block.type === "for_each_list") return emitForEachList(block, ctx, indent);
  if (block.type === "controls_if") return emitControlsIf(block, ctx, indent);
  if (ctx.kind === "xml") return emitXml(block, ctx, indent);
  if (ctx.kind === "text") return emitTextValue(block, ctx);
  return emitJson(block, ctx, indent);
}

function emitForEach(block: Block, ctx: GoEmitContext, indent: number): string {
  const name = String(block.getFieldValue("VAR") || "item");
  const ident = /^[A-Za-z_][A-Za-z0-9_]*$/.test(name) ? name : "item";
  const path = String(block.getFieldValue("PATH") || "/");
  const coll = goIndexExpr(path, ctx.loopVar ?? ".Data");
  const inner: GoEmitContext = { ...ctx, loopVar: `$${ident}` };
  const bodyBlock = block.getInputTargetBlock("DO");
  const body = bodyBlock ? emitFragment(bodyBlock, inner, indent) : "";
  const pad = "  ".repeat(indent);
  if (ctx.kind === "json") {
    return [
      `[`,
      `${pad}{{- range $i, $${ident} := (${coll}) }}`,
      `${pad}{{- if $i }},{{ end }}`,
      indentBlock(body, indent + 1),
      `${pad}{{- end }}`,
      `${"  ".repeat(Math.max(0, indent - 0))}]`,
    ].join("\n");
  }
  return `{{- range $i, $${ident} := (${coll}) }}\n${body}\n{{- end }}`;
}

function emitForEachList(block: Block, ctx: GoEmitContext, indent: number): string {
  const name = String(block.getFieldValue("VAR") || "item");
  const ident = /^[A-Za-z_][A-Za-z0-9_]*$/.test(name) ? name : "item";
  const listBlock = block.getInputTargetBlock("LIST");
  const list = listBlock ? goAction(listBlock, ctx, "raw") : "list";
  const inner: GoEmitContext = { ...ctx, loopVar: `$${ident}` };
  const bodyBlock = block.getInputTargetBlock("DO");
  const body = bodyBlock ? emitFragment(bodyBlock, inner, indent) : "";
  const coll = stripAction(list);
  if (ctx.kind === "json") {
    const pad = "  ".repeat(indent);
    return [
      `[`,
      `${pad}{{- range $i, $${ident} := (${coll}) }}`,
      `${pad}{{- if $i }},{{ end }}`,
      indentBlock(body, indent + 1),
      `${pad}{{- end }}`,
      `]`,
    ].join("\n");
  }
  return `{{- range $i, $${ident} := (${coll}) }}\n${body}\n{{- end }}`;
}

function emitControlsIf(block: Block, ctx: GoEmitContext, indent: number): string {
  const elseIfCount = Number((block as Block & { elseifCount_?: number }).elseifCount_ ?? 0);
  const hasElse = Number((block as Block & { elseCount_?: number }).elseCount_ ?? 0) > 0;
  const ifCount = elseIfCount + 1;
  const lines: string[] = [];
  for (let i = 0; i < ifCount; i++) {
    const cond = block.getInputTargetBlock(`IF${i}`);
    const body = block.getInputTargetBlock(`DO${i}`);
    const keyword = i === 0 ? "if" : "else if";
    const condStr = cond ? emitCondition(cond, ctx) : "true";
    lines.push(`{{- ${keyword} ${condStr} }}`);
    if (body) lines.push(emitStatementChainXmlOrJson(body, ctx, indent));
  }
  if (hasElse) {
    const elseBody = block.getInputTargetBlock("ELSE");
    lines.push(`{{- else }}`);
    if (elseBody) lines.push(emitStatementChainXmlOrJson(elseBody, ctx, indent));
  }
  lines.push(`{{- end }}`);
  return lines.filter((line) => line.length > 0).join("\n");
}

function emitStatementChainXmlOrJson(
  first: Block,
  ctx: GoEmitContext,
  indent: number,
): string {
  return statementChain(first)
    .map((block) => emitFragment(block, ctx, indent))
    .filter(Boolean)
    .join(ctx.kind === "json" ? ",\n" : "\n");
}

function emitXml(block: Block, ctx: GoEmitContext, indent: number): string {
  if (block.type === "xml_text") {
    const value = block.getInputTargetBlock("VALUE");
    return value ? emitTextValue(value, ctx) : String(block.getFieldValue("TEXT") ?? "");
  }
  if (block.type === "xml_attribute") return "";
  if (block.type === "text" || block.type === "text_code") return emitTextValue(block, ctx);
  if (
    block.type === "source_query" || block.type === "source_query_number" ||
    block.type === "source_query_boolean" || block.type === "source_query_node" ||
    block.type === "maps_get"
  ) {
    return goAction(block, ctx, "raw");
  }
  if (block.type === "xml_element" || isSchemaStructureBlock(block) ||
    block.type.startsWith("schema_") || block.type === "target_structure") {
    return emitXmlElement(block, ctx, indent);
  }
  return emitTextValue(block, ctx);
}

function emitXmlElement(block: Block, ctx: GoEmitContext, indent: number): string {
  const tag = xmlTagName(block);
  const xmlAttributes = xmlAttributeNames(block);
  const attrParts: string[] = [...staticAttributes(block)];
  const inner: string[] = [];

  if (block.type === "xml_element") {
    for (const child of statementChain(block.getInputTargetBlock("TARGET_children"))) {
      if (child.type === "xml_attribute") {
        const name = String(child.getFieldValue("NAME") ?? "").trim();
        if (!name) continue;
        const val = child.getInputTargetBlock("VALUE");
        attrParts.push(` ${name}="${val ? emitTextValue(val, ctx) : ""}"`);
      } else {
        inner.push(emitFragment(child, ctx, indent + 1));
      }
    }
  } else {
    for (const input of block.inputList) {
      if (!input.name.startsWith("TARGET_") && !input.name.startsWith("SCHEMA_OPT_")) {
        continue;
      }
      const fieldName = input.name.replace(/^TARGET_|^SCHEMA_OPT_/, "");
      if (input.type === STATEMENT_INPUT_TYPE) {
        const chain = statementChain(block.getInputTargetBlock(input.name));
        for (const child of chain) {
          if (child.type === "xml_attribute" || xmlAttributes.has(fieldName)) {
            const val = child.type === "xml_attribute"
              ? child.getInputTargetBlock("VALUE")
              : child;
            attrParts.push(
              ` ${fieldName}="${val ? emitTextValue(val, ctx) : emitTextValue(child, ctx)}"`,
            );
          } else {
            inner.push(emitFragment(child, ctx, indent + 1));
          }
        }
        continue;
      }
      const child = block.getInputTargetBlock(input.name);
      if (!child) continue;
      if (xmlAttributes.has(fieldName) || child.type === "xml_attribute") {
        attrParts.push(` ${fieldName}="${emitTextValue(child, ctx)}"`);
        continue;
      }
      if (isXmlChildStructure(child)) {
        inner.push(emitFragment(child, ctx, indent + 1));
        continue;
      }
      inner.push(
        `<${xmlName(fieldName)}>${emitTextValue(child, ctx)}</${xmlName(fieldName)}>`,
      );
    }
  }

  const attrs = attrParts.join("");
  if (!inner.length) {
    return block.type === "xml_element" ? `<${tag}${attrs} />` : `<${tag}${attrs}></${tag}>`;
  }
  const pad = "  ".repeat(indent);
  const innerPad = "  ".repeat(indent + 1);
  const body = inner
    .filter((line) => line.length > 0)
    .map((line) => line.split("\n").map((row, i) => (i === 0 ? `${innerPad}${row}` : row.startsWith(" ") ? row : `${innerPad}${row}`)).join("\n"))
    .join("\n");
  return `<${tag}${attrs}>\n${body}\n${pad}</${tag}>`;
}

function isXmlChildStructure(block: Block): boolean {
  return block.type === "xml_element" || block.type === "target_structure" ||
    block.type.startsWith("schema_") || block.type === "controls_if" ||
    block.type === "for_each_source" || block.type === "for_each_list" ||
    isSchemaStructureBlock(block);
}

function xmlAttributeNames(block: Block): Set<string> {
  const extra = schemaExtraStateOf(block);
  const names = new Set<string>(extra?.xmlAttributes ?? []);
  for (const field of extra?.fields ?? []) {
    if (field.xmlKind === "attribute") names.add(field.name);
  }
  return names;
}

function xmlTagName(block: Block): string {
  const slot = String(block.getFieldValue("SLOT_ID") ?? "");
  const path = slot.includes(":") ? slot.slice(slot.indexOf(":") + 1) : slot;
  const fromPath = path.split("/").filter((part) => part && !part.startsWith("@")).pop();
  if (fromPath) return fromPath;
  const name = String(block.getFieldValue("NAME") ?? "element").trim();
  return name || "element";
}

function xmlName(value: string): string {
  const safe = value.replace(/[^A-Za-z0-9_.-]/g, "_");
  return /^[A-Za-z_]/.test(safe) ? safe : `_${safe}`;
}

function staticAttributes(block: Block): string[] {
  const attrs: string[] = [];
  let i = 0;
  while (block.getField(`ATTR_NAME${i}`)) {
    const name = String(block.getFieldValue(`ATTR_NAME${i}`) ?? "");
    const valBlock = block.getInputTargetBlock(`ATTR_VALUE${i}`);
    const val = valBlock
      ? emitTextValue(valBlock, { kind: "xml" })
      : String(block.getFieldValue(`ATTR_VALUE${i}`) ?? "");
    if (name) attrs.push(` ${name}="${val}"`);
    i++;
  }
  return attrs;
}

function emitJson(block: Block, ctx: GoEmitContext, indent: number): string {
  if (block.type === "json_null") return "null";
  if (block.type === "json_boolean" || block.type === "json_value") {
    const value = block.getInputTargetBlock("VALUE");
    return value ? jsonScalar(value, ctx) : (block.type === "json_boolean" ? "false" : "null");
  }
  if (block.type === "json_array") return emitJsonArray(block, ctx, indent);
  if (block.type === "lists_create_with") return emitListsCreate(block, ctx, indent);
  if (block.type === TERM_PICK_BLOCK_TYPE) return emitTermPick(block);
  if (block.type === "code_phrase") return emitCodePhrase(block, ctx, indent);
  if (block.type === "party_self") return jsonObject([["_type", jsonString("PARTY_SELF")]], indent);
  if (block.type === "party_proxy") {
    const kind = block.getInputTargetBlock(RM_SPECIALIZATION_INPUT);
    if (kind) return emitJson(kind, ctx, indent);
    return jsonObject([["_type", jsonString("PARTY_SELF")]], indent);
  }
  if (block.type === "party_ref") return emitPartyRef(block, ctx, indent);
  if (block.type === "element" || isRmContainerBlockType(block.type)) {
    return emitRmContainer(block, ctx, indent);
  }
  if (isDataValueBlock(block)) return emitDvShell(block, ctx, indent);
  if (
    isGenericValueBlockType(block.type) || isSchemaStructureBlock(block) ||
    block.type === "json_object" || block.type === "target_structure" ||
    block.type.startsWith("schema_")
  ) {
    return emitGenericJson(block, ctx, indent);
  }
  return jsonScalar(block, ctx);
}

function emitGenericJson(block: Block, ctx: GoEmitContext, indent: number): string {
  if (isGenericValueBlockType(block.type) && block.type !== "json_object") {
    const value = block.getInputTargetBlock("VALUE");
    return value ? emitJson(value, ctx, indent) : "null";
  }
  const props: Array<[string, string]> = [];
  for (const input of block.inputList) {
    if (!input.name.startsWith("TARGET_") && !input.name.startsWith("SCHEMA_OPT_")) {
      continue;
    }
    const attr = input.name.replace(/^TARGET_|^SCHEMA_OPT_/, "");
    if (input.type === STATEMENT_INPUT_TYPE) {
      const code = emitJsonStatementList(
        block.getInputTargetBlock(input.name),
        ctx,
        indent + 1,
        jsonArrayHint(block, attr),
      );
      if (code) props.push([attr, code]);
      continue;
    }
    const child = block.getInputTargetBlock(input.name);
    if (!child) continue;
    const check = input.connection?.getCheck() ?? [];
    const checks = Array.isArray(check) ? check : check ? [check] : [];
    const prefer = checks.includes("Number")
      ? "number"
      : checks.includes("Boolean")
      ? "boolean"
      : "string";
    const code = isStructureJsonChild(child)
      ? emitJson(child, ctx, indent + 1)
      : jsonScalar(child, ctx, prefer);
    if (!isBlank(code)) props.push([attr, code]);
  }
  if (!props.length) return "{}";
  return jsonObject(props, indent);
}

function jsonArrayHint(block: Block, attr: string): boolean {
  const extra = schemaExtraStateOf(block);
  const field = extra?.fields?.find((item) => item.name === attr);
  const card = field?.card;
  if (card && (card.max === null || card.max > 1)) return true;
  return attr === "items" || attr === "children";
}

function isStructureJsonChild(block: Block): boolean {
  return block.type === "json_object" || block.type === "json_array" ||
    isSchemaStructureBlock(block) || block.type.startsWith("schema_") ||
    isRmContainerBlockType(block.type) || isDataValueBlock(block) ||
    block.type === "for_each_source" || block.type === "for_each_list" ||
    block.type === "lists_create_with";
}

function emitJsonArray(block: Block, ctx: GoEmitContext, indent: number): string {
  return emitJsonStatementList(
    block.getInputTargetBlock("TARGET_children") ??
      firstTargetStatement(block),
    ctx,
    indent,
    true,
  ) ?? "[]";
}

function firstTargetStatement(block: Block): Block | null {
  for (const input of block.inputList) {
    if (input.name.startsWith("TARGET_") && input.type === STATEMENT_INPUT_TYPE) {
      return block.getInputTargetBlock(input.name);
    }
  }
  return null;
}

function emitJsonStatementList(
  first: Block | null,
  ctx: GoEmitContext,
  indent: number,
  asArray: boolean,
): string | null {
  const blocks = statementChain(first);
  if (!blocks.length) return asArray ? "[]" : null;
  if (!asArray && blocks.length === 1 && blocks[0]!.type !== "for_each_source") {
    const code = emitJson(blocks[0]!, ctx, indent);
    return isBlank(code) ? null : code;
  }
  const loops = blocks.filter((block) =>
    block.type === "for_each_source" || block.type === "for_each_list"
  );
  const staticBlocks = blocks.filter((block) =>
    block.type !== "for_each_source" && block.type !== "for_each_list"
  );
  if (loops.length === 1 && !staticBlocks.length) {
    return emitForEachLike(loops[0]!, ctx, indent);
  }
  const parts = staticBlocks.map((block) => emitJson(block, ctx, indent + 1)).filter((p) =>
    !isBlank(p)
  );
  if (loops.length) {
    const loopBodies = loops.map((block) => emitForEachLike(block, ctx, indent + 1));
    const pad = "  ".repeat(indent);
    const staticJoined = parts.map((p) => indentBlock(p, indent + 1)).join(",\n");
    const loopPart = loopBodies.map((body) =>
      body.replace(/^\[/, "").replace(/\]$/, "")
    ).join("\n");
    return `[\n${staticJoined}${staticJoined && loopPart ? "\n" : ""}${loopPart}\n${pad}]`;
  }
  const pad = "  ".repeat(indent);
  const padI = "  ".repeat(indent + 1);
  return `[\n${parts.map((p) => `${padI}${p}`).join(",\n")}\n${pad}]`;
}

function emitForEachLike(block: Block, ctx: GoEmitContext, indent: number): string {
  if (block.type === "for_each_list") return emitForEachList(block, ctx, indent);
  return emitForEach(block, ctx, indent);
}

function emitRmContainer(block: Block, ctx: GoEmitContext, indent: number): string {
  const rmType = rmTypeOf(block);
  const props = collectRmProps(block, ctx, indent);
  if (!props.length && rmType !== "COMPOSITION") {
    if (rmType === "PARTY_SELF") {
      return jsonObject([["_type", jsonString("PARTY_SELF")]], indent);
    }
    return "";
  }
  return jsonObject([["_type", jsonString(rmType)], ...props], indent);
}

function collectRmProps(
  block: Block,
  ctx: GoEmitContext,
  indent: number,
): Array<[string, string]> {
  const rmType = rmTypeOf(block);
  const props: Array<[string, string]> = [];
  const name = String(block.getFieldValue("NAME") ?? "").trim();
  const nodeId = String(block.getFieldValue("ARCHETYPE_NODE_ID") ?? "").trim();
  if (name && shouldEmitLocatableName(rmType, name)) {
    props.push([
      "name",
      jsonObject([
        ["_type", jsonString("DV_TEXT")],
        ["value", jsonString(name)],
      ], indent + 1),
    ]);
  }
  if (nodeId) props.push(["archetype_node_id", jsonString(nodeId)]);

  if (block.type === "element") {
    const value = block.getInputTargetBlock("VALUE");
    if (value && !value.isShadow()) {
      const code = emitJson(value, ctx, indent + 1);
      if (!isBlank(code)) props.push(["value", code]);
    }
  }

  const seen = new Set<string>();
  for (const input of block.inputList) {
    if (!input.name.startsWith(RM_ATTR_INPUT_PREFIX)) continue;
    const attr = input.name.slice(RM_ATTR_INPUT_PREFIX.length);
    if (seen.has(attr)) continue;
    seen.add(attr);
    const code = emitRmAttribute(block, input.name, attr, rmType, ctx, indent);
    if (code && !isBlank(code)) props.push([attr, code]);
  }
  return props;
}

function emitRmAttribute(
  block: Block,
  inputName: string,
  attr: string,
  parentRmType: string,
  ctx: GoEmitContext,
  indent: number,
): string | null {
  const input = block.getInput(inputName);
  if (!input) return null;
  if (input.type === STATEMENT_INPUT_TYPE) {
    return emitJsonStatementList(
      block.getInputTargetBlock(inputName),
      ctx,
      indent + 1,
      isListAttribute(parentRmType, attr),
    );
  }
  const target = block.getInputTargetBlock(inputName);
  if (!target || target.isShadow()) return null;
  if (target.type === "lists_create_with") return emitListsCreate(target, ctx, indent + 1);
  if (isListAttribute(parentRmType, attr)) {
    const code = emitJson(target, ctx, indent + 1);
    if (!code || isBlank(code)) return null;
    return `[${code}]`;
  }
  let code = emitJson(target, ctx, indent + 1);
  code = wrapCodePhraseAttribute(attr, parentRmType, target, code, ctx, indent + 1);
  return isBlank(code) ? null : code;
}

function wrapCodePhraseAttribute(
  attr: string,
  parentRmType: string,
  target: Block,
  code: string,
  ctx: GoEmitContext,
  indent: number,
): string {
  if (isBlank(code) || code.includes("_type")) return code;
  const attrMeta = attributesFor(parentRmType).find((item) => item.name === attr);
  const attrType = attrMeta?.typeName ? baseRmTypeName(attrMeta.typeName) : "";
  if (attrType !== "CODE_PHRASE" && target.type !== "code_phrase") return code;
  const term = codePhraseTerminology(String(target.getFieldValue("SLOT_ID") ?? ""), attr);
  if (!term) return code;
  return emitCodePhraseObject(code, jsonString(term), ctx, indent);
}

function emitDvShell(block: Block, ctx: GoEmitContext, indent: number): string {
  const rmType = String(block.getFieldValue("RM_TYPE") || block.type.replace(/-/g, "_"))
    .toUpperCase();
  if (rmType === "CODE_PHRASE" || block.type === "code_phrase") {
    return emitCodePhrase(block, ctx, indent);
  }
  const props: Array<[string, string]> = [];
  for (const attr of attributesFor(rmType)) {
    if (!isPrimitiveRmType(attr.typeName) && attr.typeName !== "CODE_PHRASE") continue;
    const inputName = block.getInput(`FLD_${attr.name}`)
      ? `FLD_${attr.name}`
      : block.getInput(`OPTFLD_${attr.name}`)
      ? `OPTFLD_${attr.name}`
      : null;
    if (!inputName) continue;
    const child = block.getInputTargetBlock(inputName);
    if (!child) continue;
    if (child.isShadow()) {
      if (child.type === "math_number" || isEmptyShadow(child)) continue;
      const shadow = jsonScalar(child, ctx, jsonPrefer(attr.typeName, attr.name));
      if (isBlank(shadow) || shadow === '""') continue;
      props.push([attr.name, shadow]);
      continue;
    }
    const code = jsonScalar(child, ctx, jsonPrefer(attr.typeName, attr.name));
    if (isBlank(code)) continue;
    props.push([attr.name, code]);
  }
  if (rmType === "DV_QUANTITY" && !props.some((p) => p[0] === "magnitude")) {
    const mag = block.getInputTargetBlock("MAGNITUDE");
    if (mag && !mag.isShadow()) {
      props.push(["magnitude", jsonScalar(mag, ctx, "number")]);
    }
    const units = block.getFieldValue("UNITS");
    if (units) props.push(["units", jsonString(String(units))]);
  }
  if (!props.length) return "";
  return jsonObject([["_type", jsonString(rmType)], ...props], indent);
}

function jsonPrefer(typeName: string, attrName: string): "string" | "number" | "boolean" {
  if (typeName === "Boolean" || attrName === "value" && typeName.includes("BOOLEAN")) {
    return "boolean";
  }
  if (
    typeName === "Double" || typeName === "Integer" || typeName === "Real" ||
    attrName === "magnitude"
  ) return "number";
  return "string";
}

function emitCodePhrase(block: Block, ctx: GoEmitContext, indent: number): string {
  const codeBlock = block.getInputTargetBlock("FLD_code_string");
  const termBlock = block.getInputTargetBlock("FLD_terminology_id");
  const code = codeBlock ? jsonScalar(codeBlock, ctx, "string") : jsonString("");
  const term = termBlock ? jsonScalar(termBlock, ctx, "string") : jsonString("");
  if (isBlank(code) && isBlank(term)) return "";
  return emitCodePhraseObject(code, term, ctx, indent);
}

function emitCodePhraseObject(
  code: string,
  terminology: string,
  _ctx: GoEmitContext,
  indent: number,
): string {
  const termValue = terminology.startsWith("{")
    ? terminology
    : jsonObject([
      ["_type", jsonString("TERMINOLOGY_ID")],
      ["value", terminology],
    ], indent + 1);
  return jsonObject([
    ["_type", jsonString("CODE_PHRASE")],
    ["terminology_id", termValue],
    ["code_string", code],
  ], indent);
}

function emitTermPick(block: Block): string {
  const set = termSetById(block.getFieldValue("SET"));
  const rawCode = String(block.getFieldValue("CODE") ?? "");
  const code = rawCode === TERM_PICK_NONE ? "" : rawCode;
  if (!code) return "";
  const terminology = set?.terminologyId ?? "openehr";
  const rubric = set?.codes.find((item) => item.code === code)?.rubric ?? code;
  if (set?.valueRmType === "DV_CODED_TEXT") {
    return jsonObject([
      ["_type", jsonString("DV_CODED_TEXT")],
      ["value", jsonString(rubric)],
      ["defining_code", jsonObject([
        ["_type", jsonString("CODE_PHRASE")],
        ["terminology_id", jsonObject([
          ["_type", jsonString("TERMINOLOGY_ID")],
          ["value", jsonString(terminology)],
        ], 2)],
        ["code_string", jsonString(code)],
      ], 1)],
    ], 0);
  }
  return jsonObject([
    ["_type", jsonString("CODE_PHRASE")],
    ["terminology_id", jsonObject([
      ["_type", jsonString("TERMINOLOGY_ID")],
      ["value", jsonString(terminology)],
    ], 1)],
    ["code_string", jsonString(code)],
  ], 0);
}

function emitPartyRef(block: Block, ctx: GoEmitContext, indent: number): string {
  const props: Array<[string, string]> = [["_type", jsonString("PARTY_REF")]];
  const idBlock = block.getInputTargetBlock(rmAttributeInputName("id"));
  const nsBlock = block.getInputTargetBlock(rmAttributeInputName("namespace"));
  const typeBlock = block.getInputTargetBlock(rmAttributeInputName("type"));
  if (idBlock && !idBlock.isShadow()) {
    props.push([
      "id",
      jsonObject([
        ["_type", jsonString("OBJECT_ID")],
        ["value", jsonScalar(idBlock, ctx, "string")],
      ], indent + 1),
    ]);
  }
  if (nsBlock && !nsBlock.isShadow()) {
    props.push(["namespace", jsonScalar(nsBlock, ctx, "string")]);
  }
  if (typeBlock && !typeBlock.isShadow()) {
    props.push(["type", jsonScalar(typeBlock, ctx, "string")]);
  }
  if (props.length === 1) return "";
  return jsonObject(props, indent);
}

function emitListsCreate(block: Block, ctx: GoEmitContext, indent: number): string {
  const count = Number((block as Block & { itemCount_?: number }).itemCount_ ?? 0);
  const items: string[] = [];
  for (let i = 0; i < count; i++) {
    const child = block.getInputTargetBlock(`ADD${i}`);
    if (!child) continue;
    const code = emitJson(child, ctx, indent + 1);
    if (!isBlank(code)) items.push(code);
  }
  if (!items.length) return "[]";
  const pad = "  ".repeat(indent);
  const padI = "  ".repeat(indent + 1);
  return `[\n${items.map((item) => `${padI}${item}`).join(",\n")}\n${pad}]`;
}

function jsonScalar(
  block: Block,
  ctx: GoEmitContext,
  prefer: "string" | "number" | "boolean" | "raw" = "string",
): string {
  if (block.type === "json_null") return "null";
  if (block.type === "math_number") return String(block.getFieldValue("NUM") ?? "0");
  if (block.type === "logic_boolean") {
    return block.getFieldValue("BOOL") === "TRUE" ? "true" : "false";
  }
  if (block.type === "text") return jsonString(String(block.getFieldValue("TEXT") ?? ""));
  if (block.type === "text_code") {
    const lang = String(block.getFieldValue("LANG") ?? "");
    const text = String(block.getFieldValue("TEXT") ?? "");
    if (lang === "go-template") return text;
    return jsonString(text);
  }
  if (prefer === "number" || block.type === "source_query_number") {
    return goAction(block, ctx, "raw");
  }
  if (prefer === "boolean" || block.type === "source_query_boolean") {
    return goAction(block, ctx, "raw");
  }
  if (
    isDataValueBlock(block) || isRmContainerBlockType(block) ||
    block.type === TERM_PICK_BLOCK_TYPE || block.type === "code_phrase" ||
    block.type === "json_object" || block.type === "lists_create_with"
  ) {
    return emitJson(block, ctx, 0);
  }
  return goAction(block, ctx, "json-string");
}

function emitTextValue(block: Block, ctx: GoEmitContext): string {
  if (block.type === "text") return String(block.getFieldValue("TEXT") ?? "");
  if (block.type === "text_code") return String(block.getFieldValue("TEXT") ?? "");
  if (block.type === "math_number") return String(block.getFieldValue("NUM") ?? "0");
  if (block.type === "logic_boolean") {
    return block.getFieldValue("BOOL") === "TRUE" ? "true" : "false";
  }
  return goAction(block, ctx, "raw");
}

function goAction(
  block: Block,
  ctx: GoEmitContext,
  mode: "raw" | "json-string",
): string {
  if (block.type === "text_code") {
    const text = String(block.getFieldValue("TEXT") ?? "");
    if (String(block.getFieldValue("LANG") ?? "") === "go-template") return text;
    return mode === "json-string" ? jsonString(text) : text;
  }
  const serialized = blockToExpression(block);
  if (serialized) {
    try {
      const inner = emitGoExpr(parseExpression(serialized), {
        loopRoot: ctx.loopVar,
      });
      if (inner.startsWith("{{")) return inner;
      if (inner.startsWith("/*")) return mode === "json-string" ? "null" : "";
      if (mode === "json-string") return `{{ ${inner} | quote }}`;
      return `{{ ${inner} }}`;
    } catch {
      // fall through
    }
  }
  if (
    block.type === "source_query" || block.type === "source_query_number" ||
    block.type === "source_query_boolean" || block.type === "source_query_node"
  ) {
    const path = String(block.getFieldValue("EXPRESSION") ?? "");
    const inner = goIndexExpr(path, xpathRoot(path, ctx.loopVar));
    if (mode === "json-string") return `{{ ${inner} | quote }}`;
    return `{{ ${inner} }}`;
  }
  if (block.type === "maps_get") {
    const name = String(block.getFieldValue("NAME") ?? "defaults");
    const keyBlock = block.getInputTargetBlock("KEY");
    const key = keyBlock ? String(keyBlock.getFieldValue("TEXT") ?? "") : "";
    const inner = name === "defaults" || name === "Parameters"
      ? `.Parameters.${key.replace(/[^a-zA-Z0-9_]/g, "_")}`
      : `index .${name.replace(/[^a-zA-Z0-9_]/g, "_")} ${goQuote(key)}`;
    if (mode === "json-string") return `{{ ${inner} | quote }}`;
    return `{{ ${inner} }}`;
  }
  return mode === "json-string" ? "null" : "";
}

function xpathRoot(path: string, loopVar?: string): string {
  const trimmed = path.trim();
  const relative = Boolean(trimmed) && !trimmed.startsWith("$") && !trimmed.startsWith("/");
  if (relative && loopVar) return loopVar;
  return ".Data";
}

function emitCondition(block: Block, ctx: GoEmitContext): string {
  if (block.type === "logic_compare") {
    const op = String(block.getFieldValue("OP") ?? "EQ");
    const goOp = { EQ: "eq", NEQ: "ne", LT: "lt", LTE: "le", GT: "gt", GTE: "ge" }[op] ?? "eq";
    const a = block.getInputTargetBlock("A");
    const b = block.getInputTargetBlock("B");
    return `${goOp} ${inlineOperand(a, ctx)} ${inlineOperand(b, ctx)}`;
  }
  if (block.type === "logic_operation") {
    const op = String(block.getFieldValue("OP") ?? "AND").toLowerCase();
    const a = block.getInputTargetBlock("A");
    const b = block.getInputTargetBlock("B");
    return `${op} (${a ? emitCondition(a, ctx) : "true"}) (${b ? emitCondition(b, ctx) : "true"})`;
  }
  if (block.type === "logic_negate") {
    const inner = block.getInputTargetBlock("BOOL");
    return inner ? `not (${emitCondition(inner, ctx)})` : "true";
  }
  return inlineOperand(block, ctx);
}

function inlineOperand(block: Block | null, ctx: GoEmitContext): string {
  if (!block) return `""`;
  if (block.type === "text") return goQuote(String(block.getFieldValue("TEXT") ?? ""));
  if (block.type === "math_number") return String(block.getFieldValue("NUM") ?? "0");
  if (block.type === "logic_boolean") {
    return block.getFieldValue("BOOL") === "TRUE" ? "true" : "false";
  }
  const action = goAction(block, ctx, "raw");
  const inner = stripAction(action);
  return inner ? `(${inner})` : `""`;
}

function rmTypeOf(block: Block): string {
  if (block.type === "element") return "ELEMENT";
  const fromType = block.type.replace(/-/g, "_").toUpperCase();
  if (isRmContainerBlockType(block.type)) {
    const field = String(block.getFieldValue("RM_TYPE") ?? "").trim();
    if (field && (isEventFamilyType(field) || isEventFamilyType(fromType))) {
      return field.toUpperCase();
    }
    if (field && (isItemStructureFamilyType(field) || isItemStructureFamilyType(fromType))) {
      return field.toUpperCase();
    }
    return fromType;
  }
  const field = String(block.getFieldValue("RM_TYPE") ?? "").trim();
  if (field) return field.toUpperCase();
  return fromType;
}

function shouldEmitLocatableName(rmType: string, name: string): boolean {
  if (rmType === "COMPOSITION") return true;
  if (!LOCATABLE_TYPES.has(rmType)) return false;
  const generic = name.replace(/[_-]/g, " ").toUpperCase();
  return generic !== rmType && generic.replace(/\s+/g, "_") !== rmType;
}

function codePhraseTerminology(slotId: string, attrName: string): string | null {
  if (slotId.includes("//language/") || attrName === "language") return "ISO_639-1";
  if (slotId.includes("//territory/") || attrName === "territory") return "ISO_3166-1";
  if (slotId.includes("//encoding/") || attrName === "encoding") return "Unicode";
  return null;
}

function baseRmTypeName(typeName: string): string {
  const list = typeName.match(/^List<(.+)>$/);
  if (list) return baseRmTypeName(list[1]!);
  return typeName;
}

function isEmptyShadow(block: Block): boolean {
  if (block.type === "text") return String(block.getFieldValue("TEXT") ?? "") === "";
  return false;
}

function isBlank(code: string): boolean {
  const trimmed = code.trim();
  return !trimmed || trimmed === "undefined" || trimmed === "null" ||
    trimmed === '""' || trimmed === "''";
}

function jsonString(value: string): string {
  return JSON.stringify(value);
}

function jsonObject(props: Array<[string, string]>, indent: number): string {
  if (!props.length) return "{}";
  const pad = "  ".repeat(indent);
  const padI = "  ".repeat(indent + 1);
  const body = props.map(([key, value]) => `${padI}${JSON.stringify(key)}: ${value}`);
  return `{\n${body.join(",\n")}\n${pad}}`;
}

function statementChain(first: Block | null): Block[] {
  const blocks: Block[] = [];
  let current = first;
  while (current) {
    blocks.push(current);
    current = current.getNextBlock();
  }
  return blocks;
}

function indentBlock(code: string, indent: number): string {
  const pad = "  ".repeat(indent);
  return code.split("\n").map((line) => (line.length ? pad + line : line)).join("\n");
}

function stripAction(expr: string): string {
  return expr.replace(/^\{\{[-]?\s*/, "").replace(/\s*[-]?\}\}$/, "");
}

function registerSchemaTypesFromState(state: unknown): void {
  const types = new Set<string>();
  walkState(state, (type) => {
    if (type.startsWith("schema_")) types.add(type);
  });
  for (const type of types) ensureSchemaStructureType(type);
}

function walkState(node: unknown, visit: (type: string) => void): void {
  if (!node || typeof node !== "object") return;
  const rec = node as Record<string, unknown>;
  if (typeof rec.type === "string") visit(rec.type);
  if (rec.block) walkState(rec.block, visit);
  if (rec.shadow) walkState(rec.shadow, visit);
  if (rec.next) walkState(rec.next, visit);
  if (rec.inputs && typeof rec.inputs === "object") {
    for (const value of Object.values(rec.inputs as Record<string, unknown>)) {
      walkState(value, visit);
    }
  }
  if (Array.isArray(rec.blocks)) {
    for (const child of rec.blocks) walkState(child, visit);
  }
}
