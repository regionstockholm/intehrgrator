    "};",
    "",
    "declare function local:sheet-get-column($name as xs:string, $x as xs:numeric) as item()* {",
    "  let $sheet := local:sheet-of($name)",
    "  return if (empty($sheet)) then () else",
    "    for $row in local:unbox($sheet?values) return local:unbox($row)[xs:integer($x) + 1]",
    "};",
    "",
    "declare function local:sheet-get-header($name as xs:string, $x as xs:numeric) as xs:string {",
    "  let $sheet := local:sheet-of($name)",
    "  return if (empty($sheet)) then \"\" else string((local:unbox($sheet?headers)[xs:integer($x) + 1], \"\")[1])",
    "};",
    "",
    "declare function local:sheet-get-data($name as xs:string) as item()* {",
    "  let $sheet := local:sheet-of($name)",
    "  return if (empty($sheet)) then () else local:unbox($sheet?values)",
    "};",
    "",
    "declare function local:sheet-lookup($name as xs:string, $match-col as item(), $match-value as item()*, $return-col as item()*) as item()* {",
    "  let $sheet := local:sheet-of($name)",
    "  return if (empty($sheet)) then () else",
    "  let $mi := local:sheet-col($sheet, $match-col)",
    "  return if (empty($mi)) then () else",
    "  let $matched :=",
    "    for $row in local:unbox($sheet?values)",
