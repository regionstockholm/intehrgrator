/**
 * XQuery conversion script language — Mapping Model → self-contained `.xq`.
 *
 * Model B slot-manifest plus IR loops as `for $x in … return` and a pruned
 * `targetSignature` tree (`element node`). Full COMPOSITION RM XML (Model A/C)
 * remains a follow-up. Convert-time `$source`, `$defaults`, and `$sheets`
 * are external (ADR 0002 / 0005). In-app Test Run does not execute this `.xq`.
 *
 * See docs/future/xquery-export-investigation.md and docs/XQUERY_ENGINE.md.
 */
