export interface XqEmitEnv {
  /** Context item for relative source paths (`$source` or a loop variable). */
  ctx: string;
  /** Loop / grain names → XQuery NCName. */
  bind: Record<string, string>;
  warnings: string[];
}

function createXqEmitEnv(ctx = "$source"): XqEmitEnv {
  return { ctx, bind: {}, warnings: [] };
}

export function generateXQuery(model: MappingModel): string {
  const env = createXqEmitEnv();
  const body = emitMappingResult(model, env);
  const removed = (model.unsupported ?? []).filter((item) => item.reason === "removed");

  const lines: string[] = [
    'xquery version "3.1";',
    "",
    "(: Generated by intEHRgrator — Conversion Script (XQuery) :)",
    `(: Target: ${xqComment(model.templateId)} :)`,
    `(: Target instance format: ${xqComment(model.targetFormat ?? "openehr-template")} :)`,
    "(: Runtime: BaseX (preferred oracle) or Saxon-HE / eXist — see docs/XQUERY_ENGINE.md :)",
    "(: Bind $source as XPath 3.1 map (JSON via parse-json / json-doc) or XML node. :)",
    "(: Bind $defaults and $sheets as maps at convert time (not baked literals). :)",
    "(: Output: mapping-result with nested target nodes + slots. Full COMPOSITION RM XML is deferred. :)",
    "(: In-app Test Run continues to use Mapping Model + Target instance format — not this .xq. :)",
    "",
  ];

  if (removed.length) {
    for (const item of removed) {
      lines.push(
        `(: VMS-removed block ${xqComment(item.blockType)} skipped — not emitted :)` +
          (item.slotId ? ` (: slot ${xqComment(item.slotId)} :)` : ""),
      );
    }
    lines.push("");
  }

  if (env.warnings.length) {
    lines.push("(: Conversion script warnings — dynamic paths use local:*-at runtime helpers :)");
    for (const warning of env.warnings) {
      lines.push(`(:  - ${xqComment(warning)} :)`);
    }
    lines.push("");
  }

  lines.push(
    'declare namespace output = "http://www.w3.org/2010/xslt-xquery-serialization";',
    'declare namespace rm = "http://schemas.openehr.org/v1";',
    'declare namespace xsi = "http://www.w3.org/2001/XMLSchema-instance";',
    'declare namespace map = "http://www.w3.org/2005/xpath-functions/map";',
    "",
    'declare option output:method "xml";',
    'declare option output:indent "yes";',
    "",
    "declare variable $source external;",
    "declare variable $defaults as map(*) external := map {};",
    "declare variable $sheets as map(*) external := map {};",
    "",
    ...emitHelpers(),
    "",
    "declare function local:convert($source as item()*) as element(mapping-result) {",
    indent(body, 1),
    "};",
    "",
    "local:convert($source)",
    "",
  );
  return lines.join("\n");
}

function emitMappingResult(model: MappingModel, env: XqEmitEnv): string {
  const assignment = assignSlotsToLoops(model);
  const pruned = (model.targetSignature ?? [])
    .map((node) => pruneSignature(node, model))
    .filter((node): node is TargetSignatureNode => node !== null);
  const attachesInTree = new Set<string>();
  const collectAttaches = (node: TargetSignatureNode) => {
    if ((model.loops ?? []).some((loop) => loop.attachSlotId === node.slotId)) {
      attachesInTree.add(node.slotId);
    }
    for (const child of node.children) collectAttaches(child);
  };
  for (const root of pruned) collectAttaches(root);

  const parts: string[] = [`attribute template { ${xqString(model.templateId)} }`];
  const target = emitTargetTree(model, env, assignment, pruned);
  if (target) parts.push(target);
  const slots = emitSlotsElement(model, env, assignment, attachesInTree);
  if (slots) parts.push(slots);
  if (parts.length === 1) {
    return `element mapping-result {\n${indent(parts[0]!, 1)}\n  (: no mapped slots — map Target value slots in Blockly, then re-export :)\n}`;
  }
  return `element mapping-result {\n${indent(parts.join(",\n"), 1)}\n}`;
}

function emitTargetTree(
  model: MappingModel,
  env: XqEmitEnv,
  assignment: Map<string, MappingLoop>,
  roots: TargetSignatureNode[],
): string | null {
  if (!roots.length) return null;
  const children = roots
    .map((node) => emitSignatureNode(node, model, env, assignment))
    .filter(Boolean);
  if (!children.length) return null;
  return `element target {\n${indent(children.join(",\n"), 1)}\n}`;
}

function emitSlotsElement(
  model: MappingModel,
  env: XqEmitEnv,
  assignment: Map<string, MappingLoop>,
  attachesInTree: Set<string>,
): string | null {
  const loops = model.loops ?? [];
  const parts: string[] = [];

  for (const slot of model.slots) {
    const loop = assignment.get(slot.slotId);
    if (loop && attachesInTree.has(loop.attachSlotId)) continue;
    if (loop) continue;
    parts.push(emitSlot(slot, env).join("\n"));
  }

  for (const loop of loops) {
    if (attachesInTree.has(loop.attachSlotId)) continue;
    const members = model.slots.filter((slot) => assignment.get(slot.slotId) === loop);
    if (!members.length) {
      parts.push(emitEmptyLoop(loop, env));
      continue;
    }
    const inner = loopEnv(loop, env);
    const body = members.map((slot) => emitSlot(slot, inner).join("\n")).join(",\n");
    parts.push(`${emitForHead(loop, env)} return (\n${indent(body, 1)}\n)`);
  }

  if (!parts.length) return null;
  return `element slots {\n${indent(parts.join(",\n"), 1)}\n}`;
}

function emitEmptyLoop(loop: MappingLoop, env: XqEmitEnv): string {
  return `${emitForHead(loop, env)} return\n${indent(
    [
      "element loop {",
      `  attribute attach-slot-id { ${xqString(loop.attachSlotId)} },`,
      `  attribute var-name { ${xqString(loop.varName)} },`,
      `  attribute kind { ${xqString(loop.kind ?? "source")} }`,
      "}",
    ].join("\n"),
    1,
  )}`;
}

function emitSignatureNode(
  node: TargetSignatureNode,
  model: MappingModel,
  env: XqEmitEnv,
  assignment: Map<string, MappingLoop>,
): string {
  const loop = (model.loops ?? []).find((item) => item.attachSlotId === node.slotId);
  const inner = loop ? loopEnv(loop, env) : env;
  const slotMap = new Map(model.slots.map((slot) => [slot.slotId, slot]));
  const parts: string[] = [
    `attribute slot-id { ${xqString(node.slotId)} }`,
    `attribute rm-type { ${xqString(node.rmType)} }`,
  ];
  if (node.label) parts.push(`attribute label { ${xqString(node.label)} }`);
  if (loop) {
    parts.push(`attribute var-name { ${xqString(loop.varName)} }`);
    parts.push(`attribute kind { ${xqString(loop.kind ?? "source")} }`);
    if (loop.path) parts.push(`attribute path { ${xqString(loop.path)} }`);
    if (loop.collection) parts.push(`attribute collection { ${xqString(loop.collection)} }`);
  }
  const slot = slotMap.get(node.slotId);
  if (slot) parts.push(emitSlot(slot, inner).join("\n"));
  for (const child of node.children) {
    parts.push(emitSignatureNode(child, model, inner, assignment));
  }
  if (loop) {
    const inTree = signatureSubtreeIds(model, loop.attachSlotId);
    for (const extra of model.slots) {
      if (assignment.get(extra.slotId) === loop && !inTree.has(extra.slotId)) {
        parts.push(emitSlot(extra, inner).join("\n"));
      }
    }
  }
  const element = `element node {\n${indent(parts.join(",\n"), 1)}\n}`;
  if (!loop) return element;
  return `${emitForHead(loop, env)} return\n${indent(element, 1)}`;
}

function emitForHead(loop: MappingLoop, env: XqEmitEnv): string {
  const ident = xqIdent(loop.varName);
  return `for $${ident} in ${emitLoopSequence(loop, env)}`;
}

function emitLoopSequence(loop: MappingLoop, env: XqEmitEnv): string {
  if ((loop.kind ?? "source") === "list") {
    if (!loop.collection?.trim()) return "()";
    try {
      return `local:unbox(${emitXQueryExprInner(parseExpression(loop.collection), env)})`;
    } catch (e) {
      const msg = e instanceof Error ? e.message : String(e);
      return `(: unparseable collection: ${xqComment(msg)} :) ()`;
    }
  }
  const path = loop.path.trim();
  const compiled = compileSequencePath(path, "$source");
  if (compiled) return `local:unbox(${compiled})`;
  env.warnings.push(`loop ${loop.varName}: dynamic collection path uses local:nodes-at`);
  return `local:nodes-at($source, ${xqString(path)})`;
}

function loopEnv(loop: MappingLoop, env: XqEmitEnv): XqEmitEnv {
  const ident = xqIdent(loop.varName);
  return {
    ctx: `$${ident}`,
    bind: { ...env.bind, [loop.varName]: ident },
    warnings: env.warnings,
  };
}

function assignSlotsToLoops(model: MappingModel): Map<string, MappingLoop> {
  const assigned = new Map<string, MappingLoop>();
  const loops = model.loops ?? [];
  const ranked = [...loops].sort(
    (a, b) => signatureDepth(model, a.attachSlotId) - signatureDepth(model, b.attachSlotId),
  );
  for (const loop of ranked) {
    for (const id of signatureSubtreeIds(model, loop.attachSlotId)) {
      assigned.set(id, loop);
    }
  }
  const leftover = model.slots.filter((slot) =>
    !assigned.has(slot.slotId) && slotBelongsToSomeLoop(slot, loops)
  );
  if (leftover.length && loops.length) {
    for (const slot of leftover) {
      const named = loops.find((loop) => slotUsesLoopVar(slot, loop));
      if (named) assigned.set(slot.slotId, named);
      else if (loops.length === 1) assigned.set(slot.slotId, loops[0]!);
    }
  }
  return assigned;
}

function slotBelongsToSomeLoop(slot: MappingSlot, loops: MappingLoop[]): boolean {
  if (expressionUsesRelativeSourcePath(slot.expression)) return true;
  return loops.some((loop) => slotUsesLoopVar(slot, loop));
}

function slotUsesLoopVar(slot: MappingSlot, loop: MappingLoop): boolean {
  return slot.expression.includes(`var(${JSON.stringify(loop.varName)})`) ||
    slot.expression.includes(`var("${loop.varName}")`);
}

function signatureDepth(model: MappingModel, slotId: string): number {
  const walk = (nodes: TargetSignatureNode[], depth: number): number | null => {
    for (const node of nodes) {
      if (node.slotId === slotId) return depth;
      const found = walk(node.children, depth + 1);
      if (found !== null) return found;
    }
    return null;
  };
  return walk(model.targetSignature ?? [], 0) ?? 0;
}

function signatureSubtreeIds(model: MappingModel, slotId: string): Set<string> {
  const ids = new Set<string>();
  const node = findSignatureNode(model.targetSignature ?? [], slotId);
  if (!node) return ids;
  const collect = (current: TargetSignatureNode) => {
    ids.add(current.slotId);
    for (const child of current.children) collect(child);
  };
  collect(node);
  return ids;
}

function findSignatureNode(
  nodes: TargetSignatureNode[],
  slotId: string,
): TargetSignatureNode | undefined {
  for (const node of nodes) {
    if (node.slotId === slotId) return node;
    const child = findSignatureNode(node.children, slotId);
    if (child) return child;
  }
  return undefined;
}

function pruneSignature(node: TargetSignatureNode, model: MappingModel): TargetSignatureNode | null {
  const children = node.children
    .map((child) => pruneSignature(child, model))
    .filter((child): child is TargetSignatureNode => child !== null);
  const keep = model.slots.some((slot) => slot.slotId === node.slotId) ||
    (model.loops ?? []).some((loop) => loop.attachSlotId === node.slotId) ||
    children.length > 0;
  if (!keep) return null;
  return { ...node, children };
}

