import { assertEquals, assert } from "@std/assert";
import { dirname, fromFileUrl, join } from "@std/path";
import { generate, generateGoTemplate } from "@intehrgrator/core/codegen/mod.ts";
import { createEmptyModel, applyExpressionEdit } from "@intehrgrator/core/mapping_model/mod.ts";
import { runTest } from "@intehrgrator/core/test_runner/mod.ts";
import { Blockly } from "@intehrgrator/blockly/blockly_core.ts";
import { initBlocklyGenerators } from "@intehrgrator/blockly/mod.ts";
import type { MappingModel } from "@intehrgrator/types/mod.ts";

const root = join(dirname(fromFileUrl(import.meta.url)), "..");

function modelWithSlots(slots: Array<{ slotId: string; expression: string; label?: string }>): MappingModel {
  let model = createEmptyModel("test-template");
  for (const s of slots) {
    model = applyExpressionEdit(model, s.slotId, s.expression, {
      rmType: "DV_TEXT",
      returnType: "string",
      label: s.label,
    });
  }
  return model;
}

Deno.test("go-template codegen from slot expressions", () => {
  const model = modelWithSlots([
    { slotId: "systolic", expression: 'xpathNumber("$.vitals.systolic")', label: "Systolic" },
    { slotId: "name", expression: 'maps_get("defaults", "PatientName")', label: "Name" },
  ]);
  const output = generate(model, "go-template");
  assert(output.includes("Generated by intEHRgrator"), "should have header");
  assert(output.includes("index .Data"), "source query → index .Data");
  assert(output.includes(".Parameters.PatientName"), "defaults → .Parameters");
});

