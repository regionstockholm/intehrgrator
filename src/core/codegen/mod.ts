export interface ExportGenerationOptions {
  handlebarsTemplate?: string;
  precompile?: boolean;
  /** Canonical Blockly workspace JSON — preferred input for TypeScript export. */
  blocklyState?: unknown;
  /** Template Skeleton used when Blockly state is not available. */
  skeleton?: SkeletonNode[];
}

export interface ExportTargetAdapter {
  readonly id: ExportTarget;
  readonly extension: string;
  readonly mime: string;
  generate(model: MappingModel, options?: ExportGenerationOptions): string;
}

/** Fallback TypeScript export used until Blockly registers its canvas walker. */
export function generateTypeScript(
  model: MappingModel,
  options?: ExportGenerationOptions,
): string {
  if (options?.skeleton?.length) {
    return generateTypeScriptFromSkeleton(model, options.skeleton);
  }
  return generateTypeScriptFromSlots(model);
}

export function generateJava(model: MappingModel): string {
  const lines: string[] = [
    "// Generated by intEHRgrator — Conversion Script (Java / Archie)",
    `// Template: ${model.templateId}`,
    "package com.regionstockholm.intehrgrator.generated;",
    "",
    "import com.nedap.archie.rm.composition.Composition;",
    "",
    "public class ConversionScript {",
    "  public Composition convert(Object source, java.util.Map<String, Object> defaults) {",
    "    Composition composition = new Composition();",
  ];

  for (const slot of model.slots) {
    lines.push(`    // ${slot.slotId} = ${serialize(parseExpression(slot.expression))}`);
  }

  lines.push("    return composition;", "  }", "}");
  return lines.join("\n");
}

export function generateHandlebars(
  model: MappingModel,
  options: ExportGenerationOptions = {},
): string {
  const source = options.handlebarsTemplate?.trim()
    ? options.handlebarsTemplate
    : [
      "{{!-- Generated by intEHRgrator — Kintegrate-compatible Handlebars dialect --}}",
      `{{!-- Target: ${model.templateId} --}}`,
      ...model.slots.map((slot) =>
        `{{!-- ${slot.label ?? slot.slotId} --}}{{{json (slot ${JSON.stringify(slot.slotId)})}}}`
      ),
    ].join("\n");
  return options.precompile ? precompileHandlebars(source) : source;
}

const adapters = new Map<ExportTarget, ExportTargetAdapter>([
  ["typescript", {
    id: "typescript",
    extension: "ts",
    mime: "text/typescript",
    generate: generateTypeScript,
  }],
  ["java", {
    id: "java",
    extension: "java",
    mime: "text/x-java-source",
    generate: generateJava,
  }],
  ["handlebars", {
    id: "handlebars",
    extension: "hbs",
    mime: "text/x-handlebars-template",
    generate: generateHandlebars,
  }],
  ["xquery", {
    id: "xquery",
    extension: "xq",
    mime: "application/xquery",
    generate: generateXQuery,
  }],
]);

export function registerExportTargetAdapter(adapter: ExportTargetAdapter): void {
  adapters.set(adapter.id, adapter);
}

export function getExportTargetAdapter(target: ExportTarget): ExportTargetAdapter {
  const adapter = adapters.get(target);
  if (!adapter) throw new Error(`Unsupported export target: ${target}`);
  return adapter;
}

export function generate(
  model: MappingModel,
  target: ExportTarget,
  options?: ExportGenerationOptions,
): string {
  return getExportTargetAdapter(target).generate(model, options);
}
